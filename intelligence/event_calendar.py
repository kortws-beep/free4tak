import datetime

D = datetime.date


def _nth_weekday(y, m, weekday, n):
    d = D(y, m, 1)
    while d.weekday() != weekday:
        d += datetime.timedelta(days=1)
    return d + datetime.timedelta(weeks=n - 1)


def black_friday(y):
    return _nth_weekday(y, 11, 3, 4) + datetime.timedelta(days=1)   # 넷째 목요일 다음 날


