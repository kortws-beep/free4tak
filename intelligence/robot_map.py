def _master(db: str = None) -> dict:
    db = db or os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "lina_bot", "kr_theme_finance.db")
    try:
        conn = sqlite3.connect(db, timeout=10)
        try:
            return {(n or "").replace(" ", ""): c for c, n in conn.execute("SELECT code, name FROM kr_stock_master")}
        finally:
            conn.close()
    except Exception:
        return {}


def codes(names, master: dict = None) -> dict:
    master = master if master is not None else _master()
    return {n: master[n.replace(" ", "")] for n in names if n.replace(" ", "") in master}


def group_codes(group: str, master: dict = None) -> dict:
    return codes(GROUPS.get(group, {}), master)


def customer_codes(customer: str, master: dict = None) -> dict:
    return codes(CUSTOMER.get(customer, {}), master)


def find(name: str) -> list:
    """종목 이름 → [(칸 종류, 칸 이름, 설명, 출처)]."""
    out = []
    for g, d in GROUPS.items():
        if name in d:
            out.append(("밸류체인", g, *d[name]))
    for c, d in CUSTOMER.items():
        if name in d:
            out.append(("고객사", c, *d[name]))
    return out


def check(master: dict = None) -> list:
    """kr_stock_master에 없는 이름(사명 변경·오타) 목록."""
    master = master if master is not None else _master()
    names = {n for d in GROUPS.values() for n in d} | {n for d in CUSTOMER.values() for n in d}
    return sorted(n for n in names if n.replace(" ", "") not in master)


