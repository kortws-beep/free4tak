def events(y0=2016, y1=2027) -> dict:
    """{이벤트: [date, ...]} — 규칙형 + FIXED."""
    out = {k: [D.fromisoformat(x) for x in v if y0 <= int(x[:4]) <= y1] for k, v in FIXED.items()}
    ys = range(y0, y1 + 1)
    out["블랙프라이데이"] = [black_friday(y) for y in ys]
    out["광군절"] = [D(y, 11, 11) for y in ys]
    out["618"] = [D(y, 6, 18) for y in ys]
    out["연말배당"] = [D(y, 12, 31) for y in ys]          # 검증에서 '그 이전 마지막 거래일'로 맞춤
    out["실적시즌"] = [D(y, m, 5) for y in ys for m in (1, 4, 7, 10)]
    return out


def upcoming(today: datetime.date = None, days: int = 21) -> list:
    """앞으로 days일 안의 이벤트 [(date, 이름)] 날짜순."""
    today = today or datetime.date.today()
    end = today + datetime.timedelta(days=days)
    return sorted((d, k) for k, ds in events(today.year, today.year + 1).items() for d in ds if today <= d <= end)


